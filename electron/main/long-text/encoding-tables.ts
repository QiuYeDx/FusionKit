/**
 * The 2,350 Hangul syllables of KS X 1001 (rows 0xB0–0xC8), which EUC-KR text is written in. iconv-lite
 * reads `euc-kr` as cp949, whose other 8,822 syllables are rare in Korean text but are what many
 * Shift_JIS kana pairs turn into.
 */
export const KS_HANGUL: ReadonlySet<string> = (() => {
  const bytes: number[] = [];
  for (let lead = 0xb0; lead <= 0xc8; lead++) for (let trail = 0xa1; trail <= 0xfe; trail++) bytes.push(lead, trail);
  return new Set(iconv.decode(Buffer.from(bytes), 'euc-kr'));
})();
