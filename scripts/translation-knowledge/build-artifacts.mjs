import { build } from 'esbuild'
import { mkdir, writeFile, readFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import path from 'node:path'
import { buildSkillArchive, skillDirectory } from './skill-archive.mjs'

const root = fileURLToPath(new URL('../../', import.meta.url))
const check = process.argv.includes('--check')
const generated = new Map()
const schemaBundle = await build({ absWorkingDir: root, entryPoints: ['src/translation-knowledge/schemas.ts'], bundle: true, write: false, platform: 'node', format: 'esm', target: 'node18', logLevel: 'silent' })
const { knowledgePackageJsonSchema } = await import(`data:text/javascript;base64,${Buffer.from(schemaBundle.outputFiles[0].text).toString('base64')}`)
const schema = `${JSON.stringify(knowledgePackageJsonSchema(), null, 2)}\n`
generated.set('resources/translation-knowledge/knowledge-v1.schema.json', schema)
generated.set(`${skillDirectory}/references/knowledge-v1.schema.json`, schema)
const zodLicense = await readFile(path.join(root, 'node_modules/zod/LICENSE'), 'utf8')
const cli = await build({ absWorkingDir: root, entryPoints: ['scripts/translation-knowledge/cli.ts'], bundle: true, write: false, platform: 'node', format: 'esm', target: 'node18', minify: true, legalComments: 'inline', banner: { js: `// Generated by scripts/translation-knowledge/build-artifacts.mjs. FK-TK/1, Node.js >=18. Do not edit.\n/* Bundled Zod license:\n${zodLicense}\n*/` }, logLevel: 'silent' })
generated.set(`${skillDirectory}/scripts/validate.mjs`, cli.outputFiles[0].text)
const archive = await buildSkillArchive(root, generated)
generated.set('electron/main/translation-knowledge/skill-archive.generated.ts', `// Generated by scripts/translation-knowledge/build-artifacts.mjs. Do not edit.\nexport const skillArchiveName = 'fusionkit-translation-knowledge.zip';\nexport const skillArchiveBase64 = '${archive.toString('base64')}';\n`)
for (const [relative, content] of generated) {
  const destination = path.join(root, relative)
  if (check) {
    if ((await readFile(destination, 'utf8').catch(() => '')).replace(/\r\n/g, '\n') !== content) throw new Error(`Stale generated artifact: ${relative}. Run node scripts/translation-knowledge/build-artifacts.mjs`)
  } else { await mkdir(path.dirname(destination), { recursive: true }); await writeFile(destination, content) }
}
console.log(`${check ? 'Verified' : 'Generated'} ${generated.size} FK-TK/1 artifacts from the application protocol modules.`)
