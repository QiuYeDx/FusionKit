import { createHash } from 'node:crypto';
import { execFile } from 'node:child_process';
import { createWriteStream } from 'node:fs';
import { copyFile, lstat, mkdir, readFile, rename, rm, writeFile } from 'node:fs/promises';
import http from 'node:http';
import https from 'node:https';
import path from 'node:path';
import tls from 'node:tls';
import { pipeline } from 'node:stream/promises';

/**
 * Microsoft's VC++ v14 x64 redistributable, shipped with the Windows installer (decision D3).
 * The transcription server is started with PATH reduced to its own directory and System32, and that
 * directory is verified as an exact file tree, so app-local DLLs cannot work: the official runtime
 * has to be installed. Before a Windows build this stages the installer in build/vc-redist, checks
 * that Microsoft signed it, and writes its version for the NSIS script and for the application.
 */
export const VC_REDIST_URL = 'https://aka.ms/vc14/vc_redist.x64.exe';
export const VC_REDIST_DIRECTORY = 'build/vc-redist';
export const VC_REDIST_FILE = 'vc_redist.x64.exe';
export const VC_REDIST_RECORD = 'vc-redist.json';
export const VC_REDIST_VERSION_INCLUDE = 'vc-redist-version.nsh';
/** A verified local copy to use instead of the cache or a download (offline builds). */
export const VC_REDIST_PATH_ENV = 'FUSIONKIT_VC_REDIST_PATH';
export const MICROSOFT_SIGNER = 'O=Microsoft Corporation';
/**
 * The oldest runtime the bundled transcription programs can use. whisper-server.exe and its DLLs
 * are linked by the MSVC 14.51 toolset (linker 14.51, Rich header build 36247), and Microsoft
 * requires a runtime at least as new as the toolset; older ones can also crash on std::mutex's
 * constexpr constructor. The installer and the application ask for the runtime only below this
 * version; one older than the bundled redistributable but new enough is left alone, so an update
 * does not ask again just because Microsoft shipped a newer build.
 */
export const VC_RUNTIME_MINIMUM = '14.51.36247';
const MIN_BYTES = 1024 * 1024;
const MAX_BYTES = 128 * 1024 * 1024;
const DOWNLOAD_TIMEOUT_MS = 60_000;

export function vcRedistError(message, cause) {
  const error = new Error(message, cause === undefined ? undefined : { cause });
  error.code = 'vc_redist_invalid';
  return error;
}

/** "14.51.36247.0" → its parts; the runtime family is always 14.x. */
export function parseRedistVersion(text) {
  const match = /^\s*(\d{1,3})\.(\d{1,3})\.(\d{1,6})(?:\.(\d{1,6}))?\s*$/u.exec(String(text ?? ''));
  if (!match || Number(match[1]) !== 14) throw vcRedistError(`Unexpected VC++ redistributable version: ${text}`);
  const [major, minor, build, revision = 0] = match.slice(1).map(value => Number(value ?? 0));
  return { major, minor, build, revision, text: `${major}.${minor}.${build}.${revision}` };
}

export function compareRedistVersions(left, right) {
  return left.major - right.major || left.minor - right.minor || left.build - right.build || left.revision - right.revision;
}

/** The bundled version, and the minimum below which the installer runs it. */
export function renderVersionInclude(version, minimum = parseRedistVersion(VC_RUNTIME_MINIMUM)) {
  return [
    '; Generated by scripts/packaging/vc-redist.mjs before a Windows build. Do not edit.',
    `!define VC_REDIST_MAJOR ${version.major}`,
    `!define VC_REDIST_MINOR ${version.minor}`,
    `!define VC_REDIST_BUILD ${version.build}`,
    `!define VC_REDIST_VERSION "${version.text}"`,
    `!define VC_RUNTIME_MIN_MAJOR ${minimum.major}`,
    `!define VC_RUNTIME_MIN_MINOR ${minimum.minor}`,
    `!define VC_RUNTIME_MIN_BUILD ${minimum.build}`,
    '',
  ].join('\n');
}

const INSPECT_SCRIPT = [
  "$ErrorActionPreference = 'Stop'",
  '$file = $env:FUSIONKIT_VC_REDIST_INSPECT',
  '$signature = Get-AuthenticodeSignature -LiteralPath $file',
  '$info = (Get-Item -LiteralPath $file).VersionInfo',
  '[pscustomobject]@{ status = [string]$signature.Status; subject = [string]$signature.SignerCertificate.Subject;',
  '  productVersion = [string]$info.ProductVersion; fileDescription = [string]$info.FileDescription } | ConvertTo-Json -Compress',
].join('\n');

/** Authenticode status, signer and version resource, read by Windows PowerShell. */
export function inspectRedistSignature(file, { execute = execFile, env = process.env } = {}) {
  const powershell = path.join(env.SystemRoot || env.windir || 'C:\\Windows', 'System32', 'WindowsPowerShell', 'v1.0', 'powershell.exe');
  return new Promise((resolve, reject) => {
    execute(powershell, ['-NoProfile', '-NonInteractive', '-ExecutionPolicy', 'Bypass', '-Command', INSPECT_SCRIPT],
      { env: { ...env, FUSIONKIT_VC_REDIST_INSPECT: file }, windowsHide: true, timeout: 60_000, maxBuffer: 1024 * 1024 },
      (error, stdout) => {
        if (error) { reject(vcRedistError('Could not read the VC++ redistributable signature.', error)); return; }
        try { resolve(JSON.parse(String(stdout).trim())); } catch (cause) { reject(vcRedistError('Unreadable signature report.', cause)); }
      });
  });
}

/** A valid Microsoft signature on the x64 bundle; returns its version. */
export function assertMicrosoftRedist(inspection) {
  if (inspection?.status !== 'Valid') throw vcRedistError(`The VC++ redistributable signature is not valid (${inspection?.status ?? 'missing'}).`);
  if (typeof inspection.subject !== 'string' || !inspection.subject.split(/,\s*/u).includes(MICROSOFT_SIGNER)) {
    throw vcRedistError('The VC++ redistributable is not signed by Microsoft Corporation.');
  }
  if (typeof inspection.fileDescription !== 'string' || !inspection.fileDescription.includes('(x64)')) {
    throw vcRedistError('The file is not the x64 VC++ redistributable.');
  }
  return parseRedistVersion(inspection.productVersion);
}

function proxyFor(url, env) {
  const host = url.hostname.toLowerCase();
  const noProxy = env.NO_PROXY ?? env.no_proxy ?? '';
  if (noProxy.split(',').map(value => value.trim().toLowerCase()).some(rule => rule === '*' || (rule && (host === rule.replace(/^\./u, '') || host.endsWith(rule.startsWith('.') ? rule : `.${rule}`))))) return null;
  const value = url.protocol === 'https:'
    ? env.HTTPS_PROXY ?? env.https_proxy ?? env.HTTP_PROXY ?? env.http_proxy
    : env.HTTP_PROXY ?? env.http_proxy;
  if (!value) return null;
  try {
    const proxy = new URL(value.includes('://') ? value : `http://${value}`);
    return proxy.protocol === 'http:' ? proxy : null;
  } catch { return null; }
}

function connectTunnel(proxy, url, timeoutMs) {
  return new Promise((resolve, reject) => {
    const port = url.port || (url.protocol === 'https:' ? 443 : 80);
    const request = http.request({ host: proxy.hostname, port: proxy.port || 80, method: 'CONNECT', path: `${url.hostname}:${port}`,
      headers: { host: `${url.hostname}:${port}` }, timeout: timeoutMs });
    request.once('connect', (response, socket) => {
      if (response.statusCode === 200) resolve(socket);
      else { socket.destroy(); reject(vcRedistError(`The proxy refused the connection (HTTP ${response.statusCode}).`)); }
    });
    request.once('timeout', () => request.destroy(vcRedistError('The proxy did not answer in time.')));
    request.once('error', reject);
    request.end();
  });
}

async function get(url, { env, timeoutMs }) {
  const proxy = proxyFor(url, env);
  const options = { method: 'GET', headers: { 'user-agent': 'FusionKit-build' }, timeout: timeoutMs };
  if (proxy && url.protocol === 'https:') {
    const socket = await connectTunnel(proxy, url, timeoutMs);
    options.createConnection = () => tls.connect({ socket, servername: url.hostname });
    options.agent = false;
  }
  const target = proxy && url.protocol === 'http:'
    ? { ...options, host: proxy.hostname, port: proxy.port || 80, path: url.href, headers: { ...options.headers, host: url.host } }
    : options;
  const client = url.protocol === 'https:' ? https : http;
  return new Promise((resolve, reject) => {
    const request = target.host ? client.request(target) : client.request(url, target);
    request.once('response', resolve);
    request.once('timeout', () => request.destroy(vcRedistError('The download stopped answering.')));
    request.once('error', reject);
    request.end();
  });
}

/** Downloads one file, following redirects, through the HTTP(S)_PROXY of the build environment. */
export async function downloadFile(source, destination, { env = process.env, maxRedirects = 8, timeoutMs = DOWNLOAD_TIMEOUT_MS, allowHttp = false } = {}) {
  let url = new URL(source);
  for (let redirects = 0; ; redirects++) {
    if (url.protocol !== 'https:' && !(allowHttp && url.protocol === 'http:')) throw vcRedistError(`Refusing a non-https download: ${url.href}`);
    const response = await get(url, { env, timeoutMs });
    const status = response.statusCode ?? 0;
    if (status >= 300 && status < 400 && response.headers.location) {
      response.resume();
      if (redirects >= maxRedirects) throw vcRedistError('Too many redirects.');
      url = new URL(response.headers.location, url);
      continue;
    }
    if (status !== 200) { response.resume(); throw vcRedistError(`The download failed with HTTP ${status}.`); }
    const declared = Number(response.headers['content-length']);
    if (Number.isFinite(declared) && declared > MAX_BYTES) { response.resume(); throw vcRedistError('The download is unexpectedly large.'); }
    let received = 0;
    response.on('data', chunk => { received += chunk.length; if (received > MAX_BYTES) response.destroy(vcRedistError('The download is unexpectedly large.')); });
    try { await pipeline(response, createWriteStream(destination)); }
    catch (error) { await rm(destination, { force: true }); throw error; }
    if (Number.isFinite(declared) && declared !== received) { await rm(destination, { force: true }); throw vcRedistError('The download ended early.'); }
    return { url: url.href, byteSize: received };
  }
}

async function regularFile(file) {
  try {
    const stat = await lstat(file);
    return stat.isFile() && !stat.isSymbolicLink() && stat.size >= MIN_BYTES && stat.size <= MAX_BYTES;
  } catch { return false; }
}

/**
 * Stages and verifies build/vc-redist/vc_redist.x64.exe: the file named by FUSIONKIT_VC_REDIST_PATH,
 * else a cached copy, else a fresh download. A cached copy that fails the check (or is older than
 * VC_RUNTIME_MINIMUM) is downloaded again; any other failure refuses the build. Writes vc-redist.json
 * (shipped with the installer; the application reads the minimum from it) and the NSIS version defines.
 */
export async function prepareVcRedist({ projectRoot, env = process.env, download = downloadFile, inspect = inspectRedistSignature, log = () => {} }) {
  if (typeof projectRoot !== 'string' || !path.isAbsolute(projectRoot)) throw vcRedistError('The packaging project root must be absolute.');
  const directory = path.join(projectRoot, ...VC_REDIST_DIRECTORY.split('/'));
  const staged = path.join(directory, VC_REDIST_FILE);
  const minimum = parseRedistVersion(VC_RUNTIME_MINIMUM);
  await mkdir(directory, { recursive: true });
  const verify = async file => {
    if (!(await regularFile(file))) throw vcRedistError('The VC++ redistributable is missing or has an unexpected size.');
    const version = assertMicrosoftRedist(await inspect(file, { env }));
    // A redistributable that cannot bring the runtime up to what the programs need is no use to ship.
    if (compareRedistVersions(version, minimum) < 0) throw vcRedistError(`The VC++ redistributable ${version.text} is older than the ${VC_RUNTIME_MINIMUM} runtime FusionKit needs.`);
    return version;
  };
  let version, source;
  const supplied = env[VC_REDIST_PATH_ENV]?.trim();
  if (supplied) {
    const file = path.resolve(supplied);
    version = await verify(file);
    if (path.resolve(file) !== staged) await copyFile(file, staged);
    source = 'supplied';
  } else {
    if (await regularFile(staged)) {
      try { version = await verify(staged); source = 'cache'; }
      catch (error) { log(`Cached VC++ redistributable rejected (${error.message}); downloading it again.`); }
    }
    if (!version) {
      const partial = `${staged}.download`;
      await rm(partial, { force: true });
      log(`Downloading the VC++ redistributable from ${VC_REDIST_URL}`);
      await download(VC_REDIST_URL, partial, { env });
      try { version = await verify(partial); }
      catch (error) { await rm(partial, { force: true }); throw error; }
      await rm(staged, { force: true });
      await rename(partial, staged);
      source = 'download';
    }
  }
  // Hash the staged bytes themselves, after the copy or rename.
  const bytes = await readFile(staged);
  const record = { schemaVersion: 1, fileName: VC_REDIST_FILE, version: version.text, minimumVersion: VC_RUNTIME_MINIMUM,
    sha256: createHash('sha256').update(bytes).digest('hex'), byteSize: bytes.length, signer: MICROSOFT_SIGNER };
  await writeFile(path.join(directory, VC_REDIST_RECORD), `${JSON.stringify(record, null, 2)}\n`);
  await writeFile(path.join(directory, VC_REDIST_VERSION_INCLUDE), renderVersionInclude(version, minimum));
  return { ...record, source };
}
