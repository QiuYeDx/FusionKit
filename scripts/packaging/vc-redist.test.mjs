import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import fs from 'node:fs';
import http from 'node:http';
import os from 'node:os';
import path from 'node:path';
import test from 'node:test';
import { assertMicrosoftRedist, downloadFile, inspectRedistSignature, parseRedistVersion, prepareVcRedist, renderVersionInclude,
  VC_REDIST_PATH_ENV, VC_REDIST_URL, VC_RUNTIME_MINIMUM } from './vc-redist.mjs';

const VALID = Object.freeze({ status: 'Valid', subject: 'CN=Microsoft Corporation, O=Microsoft Corporation, L=Redmond, S=Washington, C=US',
  productVersion: '14.52.36500.0', fileDescription: 'Microsoft Visual C++ v14 Redistributable (x64) - 14.52.36500' });
const sha = bytes => createHash('sha256').update(bytes).digest('hex');

function tempRoot() {
  const root = fs.realpathSync(fs.mkdtempSync(path.join(os.tmpdir(), 'vc-redist-')));
  return { root, cleanup: () => fs.rmSync(root, { recursive: true, force: true }) };
}
/** A fake redistributable: big enough to pass the size check, its first byte names it. */
const fakeExe = marker => Buffer.concat([Buffer.from(marker), Buffer.alloc(1024 * 1024 + 16, 7)]);

async function listen(handler) {
  const server = http.createServer(handler);
  await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
  return { server, origin: `http://127.0.0.1:${server.address().port}`, close: () => new Promise(resolve => server.close(resolve)) };
}

test('parses the redistributable version and renders the NSIS defines', () => {
  assert.deepEqual(parseRedistVersion('14.52.36500.0'), { major: 14, minor: 52, build: 36500, revision: 0, text: '14.52.36500.0' });
  assert.deepEqual(parseRedistVersion(' 14.51.36247 '), { major: 14, minor: 51, build: 36247, revision: 0, text: '14.51.36247.0' });
  for (const value of ['', '12.0.40664.0', '14.44', 'v14.52.36500.0', '14.52.36500.0.1', undefined]) assert.throws(() => parseRedistVersion(value), error => error.code === 'vc_redist_invalid');
  assert.equal(renderVersionInclude(parseRedistVersion('14.52.36500.0')), [
    '; Generated by scripts/packaging/vc-redist.mjs before a Windows build. Do not edit.',
    '!define VC_REDIST_MAJOR 14', '!define VC_REDIST_MINOR 52', '!define VC_REDIST_BUILD 36500', '!define VC_REDIST_VERSION "14.52.36500.0"',
    '!define VC_RUNTIME_MIN_MAJOR 14', '!define VC_RUNTIME_MIN_MINOR 51', '!define VC_RUNTIME_MIN_BUILD 36247', '',
  ].join('\n'));
  // The minimum is what the bundled programs need (linked by the MSVC 14.51 toolset), not the bundled build.
  assert.equal(VC_RUNTIME_MINIMUM, '14.51.36247');
});

test('accepts only a valid Microsoft signature on the x64 bundle', () => {
  assert.equal(assertMicrosoftRedist(VALID).text, '14.52.36500.0');
  for (const changed of [{ status: 'NotSigned' }, { status: 'HashMismatch' }, { status: 'UnknownError' }, { subject: 'CN=Contoso, O=Contoso Ltd' },
    { subject: 'CN=Microsoft Corporation, O=Microsoft Corporation Evil' }, { subject: undefined },
    { fileDescription: 'Microsoft Visual C++ 2015-2022 Redistributable (x86) - 14.52.36500' }, { productVersion: '12.0.40664.0' }]) {
    assert.throws(() => assertMicrosoftRedist({ ...VALID, ...changed }), error => error.code === 'vc_redist_invalid');
  }
  assert.throws(() => assertMicrosoftRedist(null), error => error.code === 'vc_redist_invalid');
});

test('reads real Authenticode results through Windows PowerShell', { skip: process.platform !== 'win32' }, async () => {
  const notepad = path.join(process.env.SystemRoot || 'C:\\Windows', 'System32', 'notepad.exe');
  const signed = await inspectRedistSignature(notepad);
  assert.equal(signed.status, 'Valid');
  assert.ok(signed.subject.split(/,\s*/u).includes('O=Microsoft Corporation'));
  // Signed by Microsoft, but not the redistributable.
  assert.throws(() => assertMicrosoftRedist(signed), /x64 VC\+\+ redistributable/);
  const f = tempRoot();
  try {
    const unsigned = path.join(f.root, 'unsigned.exe'); fs.writeFileSync(unsigned, fakeExe('U'));
    // Not a signed file at all (Windows reports NotSigned or UnknownError for such bytes).
    const report = await inspectRedistSignature(unsigned);
    assert.notEqual(report.status, 'Valid');
    assert.throws(() => assertMicrosoftRedist(report), /not valid/);
  } finally { f.cleanup(); }
});

test('downloads an official file once, then reuses the verified cache', async () => {
  const f = tempRoot();
  try {
    const downloads = [];
    const download = async (url, destination) => { downloads.push(url); fs.writeFileSync(destination, fakeExe('D')); };
    const inspected = [];
    const inspect = async file => { inspected.push(path.basename(file)); return VALID; };
    const first = await prepareVcRedist({ projectRoot: f.root, env: {}, download, inspect });
    assert.deepEqual(downloads, [VC_REDIST_URL]);
    assert.deepEqual(inspected, ['vc_redist.x64.exe.download']);
    const directory = path.join(f.root, 'build', 'vc-redist');
    const bytes = fs.readFileSync(path.join(directory, 'vc_redist.x64.exe'));
    assert.equal(first.source, 'download');
    const record = { schemaVersion: 1, fileName: 'vc_redist.x64.exe', version: '14.52.36500.0', minimumVersion: '14.51.36247',
      sha256: sha(bytes), byteSize: bytes.length, signer: 'O=Microsoft Corporation' };
    assert.deepEqual(JSON.parse(fs.readFileSync(path.join(directory, 'vc-redist.json'), 'utf8')), record);
    assert.match(fs.readFileSync(path.join(directory, 'vc-redist-version.nsh'), 'utf8'), /!define VC_REDIST_BUILD 36500\n[^]*!define VC_RUNTIME_MIN_BUILD 36247\n/);
    assert.equal(fs.existsSync(path.join(directory, 'vc_redist.x64.exe.download')), false);

    const second = await prepareVcRedist({ projectRoot: f.root, env: {}, download, inspect });
    assert.equal(second.source, 'cache');
    assert.equal(downloads.length, 1);
    assert.deepEqual({ ...second, source: undefined }, { ...record, source: undefined });
  } finally { f.cleanup(); }
});

test('downloads again when the cached copy fails the check, and refuses a download that fails it', async () => {
  const f = tempRoot();
  try {
    const directory = path.join(f.root, 'build', 'vc-redist');
    fs.mkdirSync(directory, { recursive: true });
    fs.writeFileSync(path.join(directory, 'vc_redist.x64.exe'), fakeExe('C'));
    const inspect = async file => fs.readFileSync(file)[0] === 'C'.charCodeAt(0) ? { ...VALID, status: 'HashMismatch' } : VALID;
    const result = await prepareVcRedist({ projectRoot: f.root, env: {}, inspect, download: async (_url, destination) => fs.writeFileSync(destination, fakeExe('D')) });
    assert.equal(result.source, 'download');
    assert.equal(fs.readFileSync(path.join(directory, 'vc_redist.x64.exe'))[0], 'D'.charCodeAt(0));

    fs.rmSync(directory, { recursive: true });
    await assert.rejects(prepareVcRedist({ projectRoot: f.root, env: {}, inspect: async () => ({ ...VALID, subject: 'CN=Someone, O=Someone' }),
      download: async (_url, destination) => fs.writeFileSync(destination, fakeExe('X')) }), /not signed by Microsoft/);
    assert.deepEqual(fs.readdirSync(directory), []);
    // A redistributable older than the runtime the programs need could not repair it.
    await assert.rejects(prepareVcRedist({ projectRoot: f.root, env: {}, inspect: async () => ({ ...VALID, productVersion: '14.44.35211.0' }),
      download: async (_url, destination) => fs.writeFileSync(destination, fakeExe('O')) }), /older than the 14\.51\.36247 runtime/);
    assert.deepEqual(fs.readdirSync(directory), []);
    // A truncated download never reaches the signature check.
    await assert.rejects(prepareVcRedist({ projectRoot: f.root, env: {}, inspect: async () => VALID,
      download: async (_url, destination) => fs.writeFileSync(destination, Buffer.alloc(10)) }), /unexpected size/);
  } finally { f.cleanup(); }
});

test('uses the file named by FUSIONKIT_VC_REDIST_PATH and never downloads', async () => {
  const f = tempRoot();
  try {
    const supplied = path.join(f.root, 'offline', 'vc_redist.x64.exe');
    fs.mkdirSync(path.dirname(supplied)); fs.writeFileSync(supplied, fakeExe('S'));
    const download = async () => { throw new Error('must not download'); };
    const result = await prepareVcRedist({ projectRoot: f.root, env: { [VC_REDIST_PATH_ENV]: supplied }, download, inspect: async () => VALID });
    assert.equal(result.source, 'supplied');
    assert.deepEqual(fs.readFileSync(path.join(f.root, 'build', 'vc-redist', 'vc_redist.x64.exe')), fs.readFileSync(supplied));
    // A supplied file that fails is refused, not replaced by a download.
    await assert.rejects(prepareVcRedist({ projectRoot: f.root, env: { [VC_REDIST_PATH_ENV]: supplied }, download, inspect: async () => ({ ...VALID, status: 'NotSigned' }) }), /not valid/);
    await assert.rejects(prepareVcRedist({ projectRoot: f.root, env: { [VC_REDIST_PATH_ENV]: path.join(f.root, 'missing.exe') }, download, inspect: async () => VALID }), /missing/);
    await assert.rejects(prepareVcRedist({ projectRoot: 'relative', env: {}, download, inspect: async () => VALID }), /absolute/);
  } finally { f.cleanup(); }
});

test('downloadFile follows redirects, checks the length and refuses http and endless redirects', async () => {
  const body = fakeExe('R');
  const local = await listen((request, response) => {
    if (request.url === '/start') { response.writeHead(302, { location: '/middle' }); response.end(); return; }
    if (request.url === '/middle') { response.writeHead(301, { location: `${local.origin}/file` }); response.end(); return; }
    if (request.url === '/file') { response.writeHead(200, { 'content-length': body.length }); response.end(body); return; }
    if (request.url === '/loop') { response.writeHead(302, { location: '/loop' }); response.end(); return; }
    if (request.url === '/short') { response.writeHead(200, { 'content-length': body.length + 10 }); response.write(body.subarray(0, 100)); response.destroy(); return; }
    response.writeHead(404); response.end();
  });
  const f = tempRoot();
  try {
    const target = path.join(f.root, 'download.exe');
    const result = await downloadFile(`${local.origin}/start`, target, { env: {}, allowHttp: true });
    assert.deepEqual(result, { url: `${local.origin}/file`, byteSize: body.length });
    assert.deepEqual(fs.readFileSync(target), body);
    await assert.rejects(downloadFile(`${local.origin}/start`, target, { env: {} }), /non-https/);
    await assert.rejects(downloadFile(`${local.origin}/loop`, target, { env: {}, allowHttp: true }), /Too many redirects/);
    await assert.rejects(downloadFile(`${local.origin}/missing`, target, { env: {}, allowHttp: true }), /HTTP 404/);
    await assert.rejects(downloadFile(`${local.origin}/short`, path.join(f.root, 'short.exe'), { env: {}, allowHttp: true }));
    assert.equal(fs.existsSync(path.join(f.root, 'short.exe')), false);
  } finally { await local.close(); f.cleanup(); }
});

test('downloadFile goes through the build environment proxy and honours NO_PROXY', async () => {
  const body = fakeExe('P');
  const origin = await listen((_request, response) => { response.writeHead(200, { 'content-length': body.length }); response.end(body); });
  const seen = [];
  const proxy = await listen((request, response) => {
    seen.push(request.url);
    // Forwards an absolute-form request to the origin.
    const forwarded = http.request(request.url, { method: request.method, headers: request.headers }, upstream => {
      response.writeHead(upstream.statusCode, upstream.headers); upstream.pipe(response);
    });
    forwarded.end();
  });
  const f = tempRoot();
  try {
    await downloadFile(`${origin.origin}/redist.exe`, path.join(f.root, 'a.exe'), { env: { HTTP_PROXY: proxy.origin }, allowHttp: true });
    assert.deepEqual(seen, [`${origin.origin}/redist.exe`]);
    assert.deepEqual(fs.readFileSync(path.join(f.root, 'a.exe')), body);
    await downloadFile(`${origin.origin}/redist.exe`, path.join(f.root, 'b.exe'), { env: { HTTP_PROXY: proxy.origin, NO_PROXY: '127.0.0.1' }, allowHttp: true });
    assert.equal(seen.length, 1);
  } finally { await origin.close(); await proxy.close(); f.cleanup(); }
});
