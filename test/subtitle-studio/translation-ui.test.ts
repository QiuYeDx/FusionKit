import { afterAll, describe, expect, it } from 'vitest';
import { _electron as electron, expect as uiExpect, type ElectronApplication } from 'playwright/test';
import { createServer, type Server } from 'node:http';
import { mkdtemp, mkdir, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import path from 'node:path';

describe.runIf(process.env.FUSIONKIT_STUDIO_E2E === '1')('Subtitle Studio translation workspace', () => {
  let app: ElectronApplication | undefined;
  let server: Server | undefined;
  let root: string;
  afterAll(async () => {
    await app?.close();
    server?.closeAllConnections();
    await new Promise<void>(resolve => server ? server.close(() => resolve()) : resolve());
    if (root) await rm(root, { recursive: true, force: true });
  });
  it('plans and translates through native IPC, persists targets and fits narrow windows', async () => {
    root = await mkdtemp(path.join(tmpdir(), 'studio-translation-ui-'));
    const artifacts = path.resolve('test-results/subtitle-studio-translation');
    await mkdir(artifacts, { recursive: true });
    const requests: any[] = [];
    let forceOutputLimit = false;
    let releaseSecond: () => void = () => {};
    const second = new Promise<void>(resolve => { releaseSecond = resolve; });
    server = createServer(async (request, response) => {
      let body = '';
      for await (const chunk of request) body += chunk.toString();
      const parsed = JSON.parse(body);
      const payload = JSON.parse(parsed.messages[1].content);
      requests.push(parsed);
      const requestIndex = requests.length;
      if (requestIndex === 2) await second;
      response.setHeader('Content-Type', 'application/json');
      if (forceOutputLimit || parsed.thinking?.type !== 'disabled') {
        response.end(JSON.stringify({ choices: [{ finish_reason: 'length', message: { content: '{"items":[' } }], usage: { prompt_tokens: 121, completion_tokens: 4096, total_tokens: 4217 } }));
        return;
      }
      response.end(JSON.stringify({ choices: [{ finish_reason: 'stop', message: { content: JSON.stringify({ items: payload.items.map((item: { id: string }) => ({ id: item.id, text: `译文 ${item.id}：保留每一个细节。` })).reverse() }) } }], ...(requestIndex === 2 ? {} : { usage: { prompt_tokens: 120, completion_tokens: 60, total_tokens: 180 } }) }));
    });
    await new Promise<void>(resolve => server!.listen(0, '127.0.0.1', resolve));
    const port = (server.address() as { port: number }).port;
    const name = '字幕翻译-长短正文与上下文-September-2026.srt';
    const source = Array.from({ length: 6 }, (_, i) => `${i + 41}\n00:00:${String(i * 3).padStart(2, '0')},000 --> 00:00:${String(i * 3 + 2).padStart(2, '0')},000\n${i === 2 ? 'A longer sentence with details. '.repeat(8) : `A quiet workshop, scene ${i + 1}.`}\n`).join('\n');
    await writeFile(path.join(root, name), source);
    app = await electron.launch({ args: ['.', `--user-data-dir=${path.join(root, 'profile')}`], cwd: process.cwd(), env: { ...process.env, VITE_DEV_SERVER_URL: '', NODE_ENV: 'test' } });
    const page = await app.firstWindow();
    const errors: string[] = []; page.on('pageerror', error => errors.push(error.message));
    await page.evaluate(port => {
      localStorage.setItem('lang', 'zh');
      localStorage.setItem('fusionkit-theme', JSON.stringify({ state: { theme: 'light' }, version: 0 }));
      localStorage.setItem('fusionkit-model', JSON.stringify({ version: 5, state: { profiles: [{ id: 'studio-fixture', name: 'DeepSeek-v4-flash', provider: 'DeepSeek', apiKey: 'synthetic-key', baseUrl: `http://127.0.0.1:${port}`, modelKey: 'deepseek-v4-flash', apiFormat: 'chat_completions', tokenPricing: { inputTokensPerMillion: 0, outputTokensPerMillion: 0 } }], assignment: { taskExecution: 'studio-fixture', agent: null }, audioProfiles: [], audioAssignment: {} } }));
      location.hash = '/tools/subtitle/studio';
    }, port);
    await page.reload();
    await page.getByTestId('subtitle-studio').waitFor();
    await page.waitForFunction(() => !document.querySelector('.app-loading-wrap') && !document.querySelector('#app-loading-style'));
    const window = await app.browserWindow(page);
    await window.evaluate(win => win.setSize(1280, 860));
    await app.evaluate(({ dialog }, file) => { dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [file] }); }, path.join(root, name));
    await page.getByRole('button', { name: '打开字幕文件', exact: true }).click();
    await uiExpect(page.locator('.studio-cue-table tbody tr')).toHaveCount(6);
    await page.getByRole('button', { name: '翻译', exact: true }).click();
    await page.locator('.studio-translation-advanced summary').click();
    await page.getByRole('spinbutton', { name: '上下文窗口（tokens）' }).fill('2048');
    await page.getByRole('spinbutton', { name: '每批输出上限（tokens）' }).fill('256');
    await page.getByRole('textbox', { name: '翻译要求（可选）' }).fill('预算'.repeat(1900));
    await page.getByRole('button', { name: '计算用量', exact: true }).click();
    await uiExpect(page.locator('.studio-translation-error')).toBeVisible();
    await page.getByRole('button', { name: '取消', exact: true }).click();
    await uiExpect(page.getByRole('button', { name: '重试', exact: true })).toHaveCount(0);
    await page.getByRole('button', { name: '关闭提示', exact: true }).click();
    expect(requests).toHaveLength(0);
    await page.getByRole('button', { name: '翻译', exact: true }).click();
    await page.getByRole('textbox', { name: '翻译要求（可选）' }).fill('');
    await page.locator('.studio-translation-advanced summary').click();
    await page.getByRole('spinbutton', { name: '上下文窗口（tokens）' }).fill('32768');
    await page.getByRole('spinbutton', { name: '每批输出上限（tokens）' }).fill('4096');
    await page.getByRole('spinbutton', { name: '每批字幕上限' }).fill('2');
    await page.getByRole('button', { name: '计算用量', exact: true }).click();
    await uiExpect(page.locator('.studio-translation-plan')).toBeVisible();
    await page.screenshot({ path: path.join(artifacts, 'plan-desktop.png'), animations: 'disabled' });
    await page.getByRole('button', { name: '开始翻译', exact: true }).click();
    await uiExpect(page.locator('.studio-target-text').filter({ hasText: '译文 u1' })).toBeVisible();
    await uiExpect(page.locator('.studio-translation-status')).toHaveAttribute('data-state', 'running');
    await page.screenshot({ path: path.join(artifacts, 'running-desktop.png'), animations: 'disabled' });
    releaseSecond();
    await uiExpect(page.locator('.studio-translation-status')).toHaveAttribute('data-state', 'completed', { timeout: 15000 });
    await uiExpect(page.locator('.studio-translation-status')).toContainText('未知');
    expect(requests).toHaveLength(3);
    expect(requests.every(request => request.thinking?.type === 'disabled')).toBe(true);
    expect(JSON.stringify(requests)).not.toContain(name);
    expect(JSON.stringify(requests)).not.toContain('00:00:');
    expect(JSON.parse(requests[1].messages[1].content).context.priorModelTranslations).toHaveLength(2);
    await page.screenshot({ path: path.join(artifacts, 'completed-desktop.png'), animations: 'disabled' });
    await window.evaluate(win => win.setSize(786, 540));
    await page.waitForTimeout(350);
    expect(await page.locator('.studio-reader-footer').evaluate(element => element.getBoundingClientRect().bottom <= document.querySelector('.fixed.bottom-0')!.getBoundingClientRect().top)).toBe(true);
    expect(await page.locator('.studio, .studio-reader').evaluateAll(elements => elements.every(element => element.scrollWidth <= element.clientWidth + 1))).toBe(true);
    await page.screenshot({ path: path.join(artifacts, 'completed-narrow.png'), animations: 'disabled' });
    await page.getByRole('button', { name: '翻译', exact: true }).click();
    await page.screenshot({ path: path.join(artifacts, 'plan-narrow.png'), animations: 'disabled' });
    await page.getByRole('button', { name: '取消', exact: true }).click();
    await page.evaluate(() => localStorage.setItem('fusionkit-theme', JSON.stringify({ state: { theme: 'dark' }, version: 0 })));
    await page.reload();
    await page.waitForFunction(() => !document.querySelector('.app-loading-wrap') && !document.querySelector('#app-loading-style'));
    await uiExpect(page.locator('.studio-translation-status')).toHaveAttribute('data-state', 'completed');
    await uiExpect(page.locator('.studio-target-text').filter({ hasText: '译文 u1' })).toBeVisible();
    expect(requests).toHaveLength(3);
    await page.screenshot({ path: path.join(artifacts, 'completed-dark-narrow.png'), animations: 'disabled' });

    const limitedName = '52-cues-output-limit.lrc';
    await writeFile(path.join(root, limitedName), Array.from({ length: 52 }, (_, i) => `[00:${String(i).padStart(2, '0')}.00]A quiet workshop, scene ${i + 1}.`).join('\n'));
    forceOutputLimit = true;
    await window.evaluate(win => win.setSize(1280, 860));
    await app.evaluate(({ dialog }, file) => { dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [file] }); }, path.join(root, limitedName));
    await page.getByRole('button', { name: '打开字幕文件', exact: true }).click();
    await uiExpect(page.locator('.studio-cue-table tbody tr')).toHaveCount(52);
    await page.getByRole('button', { name: '翻译', exact: true }).click();
    await page.getByRole('button', { name: '计算用量', exact: true }).click();
    await uiExpect(page.locator('.studio-translation-plan')).toBeVisible();
    await page.getByRole('button', { name: '开始翻译', exact: true }).click();
    const failedStatus = page.locator('.studio-translation-status');
    await uiExpect(failedStatus).toHaveAttribute('data-state', 'failed', { timeout: 15000 });
    await uiExpect(failedStatus).toContainText('已达每批输出上限，本批译文未保存。请减少每批字幕或提高输出上限。');
    await uiExpect(failedStatus).toContainText('0 / 2 批');
    await uiExpect(failedStatus).toContainText('实际 tokens：输入 121 · 输出 4,096');
    await uiExpect(page.locator('.studio-target-text').filter({ hasText: '未翻译' })).toHaveCount(52);
    await uiExpect(page.getByRole('button', { name: '重试', exact: true })).toHaveCount(0);
    await uiExpect(page.getByRole('button', { name: '翻译', exact: true })).toBeEnabled();
    expect(requests).toHaveLength(4);
    expect(requests[3].thinking).toEqual({ type: 'disabled' });
    expect(requests[3].max_tokens).toBe(4096);
    expect(JSON.parse(requests[3].messages[1].content).items).toHaveLength(32);
    await page.screenshot({ path: path.join(artifacts, 'output-limit-desktop.png'), animations: 'disabled' });
    await window.evaluate(win => win.setSize(786, 540));
    await page.waitForTimeout(350);
    expect(await failedStatus.evaluate(element => element.scrollWidth <= element.clientWidth + 1)).toBe(true);
    expect(await page.locator('.studio-reader-footer').evaluate(element => element.getBoundingClientRect().bottom <= document.querySelector('.fixed.bottom-0')!.getBoundingClientRect().top)).toBe(true);
    await page.screenshot({ path: path.join(artifacts, 'output-limit-narrow.png'), animations: 'disabled' });
    expect(requests).toHaveLength(4);
    expect(errors).toEqual([]);
  }, 90000);
});
